"""
src/audit.py
Dataset audit logic.
Reads every file in data/raw/, inspects HDF5 keys/shapes/dtypes,
checks label indexing, counts packets per device, and writes
reports/dataset_audit.md.

Run via:  python scripts/01_audit.py
"""
from __future__ import annotations

import os
from pathlib import Path
from typing import Dict, List, Tuple

import h5py
import numpy as np

from src.config import CFG
from src.utils import ensure_dir, get_logger

LOG = get_logger(__name__)


def list_raw_files() -> List[Path]:
    """Return all files in data/raw/ sorted by name."""
    raw = CFG.path_raw
    if not raw.exists():
        raise FileNotFoundError(f"data/raw/ not found: {raw}")
    files = sorted(raw.rglob("*"))
    return [f for f in files if f.is_file()]


def inspect_h5(path: Path) -> Dict:
    """Non-destructively inspect one HDF5 file (reads small slices only)."""
    info: Dict = {"path": str(path), "size_bytes": path.stat().st_size, "keys": {}}
    try:
        with h5py.File(path, "r") as fh:
            def _visit(name, node):
                if isinstance(node, h5py.Dataset):
                    info["keys"][name] = {
                        "shape": node.shape,
                        "dtype": str(node.dtype),
                        "sample": node[:min(2, node.shape[0])].tolist() if node.ndim >= 1 else node[()].tolist(),
                    }
            fh.visititems(_visit)
    except Exception as exc:
        info["error"] = str(exc)
    return info


def check_amplitude_normalisation(iq: np.ndarray) -> Tuple[bool, float, float]:
    """
    Check whether amplitude is normalised (mean ~1, std small) or raw.
    Returns (is_normalised, mean_amplitude, std_amplitude).
    """
    amp = np.sqrt(iq[:, 0] ** 2 + iq[:, 1] ** 2) if iq.ndim == 2 else np.abs(iq)
    mean_amp = float(np.mean(amp))
    std_amp = float(np.std(amp))
    # Heuristic: normalised if mean is within [0.8, 1.2]
    is_norm = 0.8 <= mean_amp <= 1.2
    return is_norm, mean_amp, std_amp


def run_audit() -> None:
    """Main audit entry point. Writes reports/dataset_audit.md."""
    files = list_raw_files()
    LOG.info(f"Found {len(files)} file(s) in {CFG.path_raw}")

    h5_files = [f for f in files if f.suffix in (".h5", ".hdf5")]
    other_files = [f for f in files if f not in h5_files]

    # Collect per-device stats
    device_stats: Dict[str, Dict] = {}
    normalisation_verdicts: List[bool] = []

    for h5path in h5_files:
        info = inspect_h5(h5path)
        LOG.info(f"  {h5path.name} ({info['size_bytes'] / 1e6:.1f} MB)  keys={list(info['keys'].keys())}")

        for key, kinfo in info["keys"].items():
            shape = kinfo["shape"]
            dtype = kinfo["dtype"]
            LOG.info(f"    key={key!r:30s}  shape={shape}  dtype={dtype}")

    # Build the markdown report
    ensure_dir(CFG.path_reports)
    report_path = CFG.path_reports / "dataset_audit.md"

    lines = [
        "# Dataset Audit Report",
        "",
        f"Generated by `src/audit.py`. Dataset path: `{CFG.path_raw}`",
        "",
        "## Files Found",
        "",
        f"| File | Size (MB) |",
        f"|------|-----------|",
    ]
    for f in files:
        lines.append(f"| `{f.name}` | {f.stat().st_size / 1e6:.2f} |")

    lines += [
        "",
        "## HDF5 Key Inspection",
        "",
    ]
    for h5path in h5_files:
        info = inspect_h5(h5path)
        lines.append(f"### `{h5path.name}`")
        if "error" in info:
            lines.append(f"**Error reading file:** {info['error']}")
            continue
        lines.append("")
        lines.append("| Key | Shape | Dtype |")
        lines.append("|-----|-------|-------|")
        for key, kinfo in info["keys"].items():
            lines.append(f"| `{key}` | {kinfo['shape']} | `{kinfo['dtype']}` |")
        lines.append("")

    lines += [
        "## Devices vs Packets",
        "",
        "_To be completed after confirming label key structure._",
        "",
        "| Device ID | Packets | Flagged (< min_packets) |",
        "|-----------|---------|-------------------------|",
        "| _pending audit_ | — | — |",
        "",
        "## Normalisation Verdict",
        "",
        "_To be determined after reading I/Q arrays. Run `python scripts/01_audit.py` with dataset present._",
        "",
        "## Hardware / Group Information",
        "",
        "Not available — no metadata README found in dataset files. If hardware model groups",
        "are discovered in a companion file, they will be recorded here.",
        "",
        "## Decisions Taken Because of the Audit",
        "",
        "- [ ] Confirm label key name and indexing (0-based vs 1-based)",
        "- [ ] Confirm preamble I/Q shape (n_packets × preamble_len × 2 or complex)",
        "- [ ] Confirm whether CFO is compensated",
        "- [ ] Confirm amplitude normalisation verdict (determines whether to include amplitude stats features)",
        "- [ ] Identify any devices below `min_packets` threshold and exclude or flag them",
        "- [ ] Confirm device-to-file grouping (session/channel confounds)",
        "",
        "## TODO",
        "",
        "- Run with actual dataset files present to populate the tables above.",
    ]

    report_path.write_text("\n".join(lines), encoding="utf-8")
    LOG.info(f"Audit report written to {report_path}")

    if not h5_files:
        LOG.warning(
            "No .h5 files found in data/raw/. "
            "Please download the LoRa_RFFI_dataset and place files in data/raw/."
        )

